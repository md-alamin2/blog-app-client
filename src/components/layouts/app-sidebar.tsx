export function AppSidebar({
  user,
  ...props
}: {
  user: UserType & React.ComponentProps<typeof Sidebar>;
}) {

  let routes: Route[] = []

  switch (user.role) {
    case Roles.admin:
      routes = adminRoutes
      break;
    case Roles.user:
      routes = userRoutes
      break;
  
    default:
      routes =[]
      break;
  }

  return (
    <Sidebar {...props}>
      <SidebarContent>
        {routes.map((item) => (
          <SidebarGroup key={item.title}>
            <SidebarGroupLabel>{item.title}</SidebarGroupLabel>
            <SidebarGroupContent>
              <SidebarMenu>
                {item.items.map((item) => (
                  <SidebarMenuItem key={item.title}>
                    <SidebarMenuButton
                      // isActive={item.isActive}
                      render={<Link href={item.url} />}
                    >
                      {item.title}
                    </SidebarMenuButton>
                  </SidebarMenuItem>
                ))}
              </SidebarMenu>
            </SidebarGroupContent>
          </SidebarGroup>
        ))}
      </SidebarContent>
      <SidebarRail />
    </Sidebar>
  );
}
